"""Exploratory data analysis + a simple regression for the student-performance dataset.

Run:  python eda.py
Outputs: images/*.png and results.md
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no display needed
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).parent
IMG = ROOT / "images"
TARGET = "exam_score"
FEATURES = ["study_hours_per_week", "attendance_pct", "sleep_hours", "prior_gpa", "tutoring", "internet_access"]


def load_and_clean(path: Path) -> tuple[pd.DataFrame, dict]:
    df = pd.read_csv(path)
    report = {"rows_raw": len(df), "missing_before": df.isna().sum()[lambda s: s > 0].to_dict()}

    before = len(df)
    df = df.drop_duplicates(subset="student_id").copy()
    report["duplicates_removed"] = before - len(df)

    # Median imputation for the numeric columns that have gaps (robust to outliers).
    for col, n in report["missing_before"].items():
        df[col] = df[col].fillna(df[col].median())
    report["rows_clean"] = len(df)
    assert df.isna().sum().sum() == 0
    return df, report


def plot_all(df: pd.DataFrame, corr: pd.DataFrame, slope: float, intercept: float) -> None:
    IMG.mkdir(exist_ok=True)
    plt.rcParams.update({"figure.dpi": 130, "axes.spines.top": False, "axes.spines.right": False})

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.hist(df[TARGET], bins=25, color="#2563eb", edgecolor="white")
    ax.axvline(df[TARGET].mean(), color="#dc2626", ls="--", label=f"mean = {df[TARGET].mean():.1f}")
    ax.set(title="Distribution of exam scores", xlabel="Exam score", ylabel="Students")
    ax.legend()
    fig.tight_layout(); fig.savefig(IMG / "score_distribution.png"); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.scatter(df["study_hours_per_week"], df[TARGET], s=14, alpha=0.5, color="#2563eb")
    xs = np.array([df["study_hours_per_week"].min(), df["study_hours_per_week"].max()])
    ax.plot(xs, intercept + slope * xs, color="#dc2626", lw=2, label=f"fit: +{slope:.2f} pts per extra hour")
    ax.set(title="Study time vs exam score", xlabel="Study hours per week", ylabel="Exam score")
    ax.legend()
    fig.tight_layout(); fig.savefig(IMG / "study_vs_score.png"); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.4, 5.4))
    im = ax.imshow(corr.values, cmap="coolwarm", vmin=-1, vmax=1)
    ax.set_xticks(range(len(corr)), corr.columns, rotation=45, ha="right")
    ax.set_yticks(range(len(corr)), corr.columns)
    for i in range(len(corr)):
        for j in range(len(corr)):
            ax.text(j, i, f"{corr.values[i, j]:.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im, ax=ax, shrink=0.8)
    ax.set_title("Correlation matrix")
    fig.tight_layout(); fig.savefig(IMG / "correlation_heatmap.png"); plt.close(fig)

    fig, ax = plt.subplots(figsize=(5, 4))
    groups = [df.loc[df.tutoring == 0, TARGET], df.loc[df.tutoring == 1, TARGET]]
    ax.boxplot(groups, tick_labels=["No tutoring", "Tutoring"], patch_artist=True,
               boxprops=dict(facecolor="#bfdbfe"), medianprops=dict(color="#dc2626"))
    ax.set(title="Exam score by tutoring", ylabel="Exam score")
    fig.tight_layout(); fig.savefig(IMG / "tutoring_boxplot.png"); plt.close(fig)


def fit_linear_model(df: pd.DataFrame, seed: int = 42) -> dict:
    """Ordinary least squares on standardised features, evaluated on a held-out 20% test set."""
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(df))
    cut = int(0.8 * len(df))
    train, test = df.iloc[idx[:cut]], df.iloc[idx[cut:]]

    mu, sd = train[FEATURES].mean(), train[FEATURES].std()
    Xtr = np.c_[np.ones(len(train)), ((train[FEATURES] - mu) / sd).to_numpy()]
    Xte = np.c_[np.ones(len(test)), ((test[FEATURES] - mu) / sd).to_numpy()]
    beta, *_ = np.linalg.lstsq(Xtr, train[TARGET].to_numpy(), rcond=None)

    pred = Xte @ beta
    resid = test[TARGET].to_numpy() - pred
    ss_res, ss_tot = (resid**2).sum(), ((test[TARGET] - test[TARGET].mean()) ** 2).sum()
    return {
        "r2": 1 - ss_res / ss_tot,
        "rmse": float(np.sqrt((resid**2).mean())),
        "coef": pd.Series(beta[1:], index=FEATURES, name="effect_points").sort_values(key=abs, ascending=False),
        "n_train": len(train),
        "n_test": len(test),
    }


def main() -> None:
    df, report = load_and_clean(ROOT / "data" / "students.csv")
    corr = df[FEATURES + [TARGET]].corr()
    slope, intercept = np.polyfit(df["study_hours_per_week"], df[TARGET], 1)
    model = fit_linear_model(df)
    plot_all(df, corr, slope, intercept)

    lines = [
        "# Results (auto-generated by eda.py)",
        "",
        "> The dataset is **synthetic** (see generate_data.py); these numbers demonstrate the workflow, not real-world facts.",
        "",
        "## Data cleaning",
        f"- Raw rows: {report['rows_raw']}; duplicates removed: {report['duplicates_removed']}; clean rows: {report['rows_clean']}",
        f"- Missing values filled with the column median: {report['missing_before']}",
        "",
        "## Summary statistics",
        df[FEATURES + [TARGET]].describe().round(2).to_markdown(),
        "",
        "## Correlation with exam score",
        corr[TARGET].drop(TARGET).sort_values(ascending=False).round(3).to_markdown(),
        "",
        f"## Linear regression (train {model['n_train']} / test {model['n_test']})",
        f"- Test R^2: **{model['r2']:.3f}**, RMSE: **{model['rmse']:.2f}** points",
        f"- Simple fit: each extra study hour per week is associated with **{slope:+.2f}** points",
        "",
        "Standardised coefficients (effect of +1 standard deviation):",
        model["coef"].round(2).to_markdown(),
        "",
    ]
    (ROOT / "results.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
